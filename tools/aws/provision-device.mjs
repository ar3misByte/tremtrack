#!/usr/bin/env node
// Registers one headset with AWS IoT Core and writes the files the firmware and the simulator need.
//
//   node tools/aws/provision-device.mjs --thing htm-01 --owner "ap-south-1:xxxxxxxx-...." [--profile p] [--region ap-south-1]
//
// --owner is the user's Cognito identity id: the app shows it after sign-in (Settings > Cloud), or use
//         tools/aws/cloud-e2e.mjs --create-user to make a test user and print it.
// Creates: an IoT thing (attribute owner=<identity id>), a certificate + private key (kept only on this
// computer, in tools/aws/out/<thing>/, which is git-ignored), attaches the device policy from the stack.
// Writes:  tools/aws/out/<thing>/{certificate.pem.crt, private.pem.key, AmazonRootCA1.pem, devsim.json}
//          firmware/tremor_monitor/device_config.h   (git-ignored; Wi-Fi is NOT stored here, see firmware/README.md)
import { mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { args, aws, ok, opts, outDir, root, stackOutputs } from './lib.mjs';

const a = args();
const o = opts(a);
const thing = a.thing;
const owner = a.owner;
if (!/^[A-Za-z0-9_-]{1,64}$/.test(thing ?? '')) { console.error('--thing NAME required (letters, digits, - and _)'); process.exit(2); }
if (!/^[a-z]{2}-[a-z]+-\d:[0-9a-f-]{36}$/.test(owner ?? '')) { console.error('--owner "<region>:<uuid>" required: the Cognito identity id of the user who will own this device'); process.exit(2); }

const out = stackOutputs(o);
if (!out.DevicePolicyName) { console.error('Stack outputs not found. Deploy first: npm run cdk:deploy'); process.exit(1); }
const dir = join(outDir, thing);
if (existsSync(join(dir, 'private.pem.key')) && a.force !== 'true') { console.error(`${dir} already has a key. Use --force to issue a new certificate (the old one stays active until you deprovision it).`); process.exit(1); }
mkdirSync(dir, { recursive: true });

console.log(`Provisioning ${thing} for ${owner} in ${o.region}`);
const endpoint = aws(['iot', 'describe-endpoint', '--endpoint-type', 'iot:Data-ATS'], o).endpointAddress;
ok(`endpoint ${endpoint}`);
try { aws(['iot', 'create-thing', '--thing-name', thing, '--attribute-payload', JSON.stringify({ attributes: { owner } })], o); ok('thing created'); }
catch (e) {
  if (!/ResourceAlreadyExists/.test(e.message)) throw e;
  aws(['iot', 'update-thing', '--thing-name', thing, '--attribute-payload', JSON.stringify({ attributes: { owner }, merge: true })], o);
  ok('thing existed; owner attribute updated');
}
const cert = aws(['iot', 'create-keys-and-certificate', '--set-as-active'], o);
writeFileSync(join(dir, 'certificate.pem.crt'), cert.certificatePem);
writeFileSync(join(dir, 'private.pem.key'), cert.keyPair.PrivateKey, { mode: 0o600 });
ok(`certificate ${cert.certificateId.slice(0, 12)}... (private key saved locally only)`);
aws(['iot', 'attach-policy', '--policy-name', out.DevicePolicyName, '--target', cert.certificateArn], o);
aws(['iot', 'attach-thing-principal', '--thing-name', thing, '--principal', cert.certificateArn], o);
ok(`policy ${out.DevicePolicyName} attached, certificate attached to the thing`);
const ca = await (await fetch('https://www.amazontrust.com/repository/AmazonRootCA1.pem')).text();
if (!ca.includes('BEGIN CERTIFICATE')) throw new Error('could not download AmazonRootCA1.pem');
writeFileSync(join(dir, 'AmazonRootCA1.pem'), ca);
ok('Amazon Root CA 1 downloaded');

const cfg = { endpoint, region: o.region, thing, owner, certificateId: cert.certificateId, cert: join(dir, 'certificate.pem.crt'), key: join(dir, 'private.pem.key'), ca: join(dir, 'AmazonRootCA1.pem') };
writeFileSync(join(dir, 'devsim.json'), JSON.stringify(cfg, null, 2));
ok(`simulator config ${join(dir, 'devsim.json')}`);

const raw = (s) => `R"PEM(\n${s.trim()}\n)PEM"`;
const header = `// GENERATED by tools/aws/provision-device.mjs for thing "${thing}". DO NOT COMMIT (git-ignored).
// Contains this device's private key. Re-run the script with --force to replace it.
#pragma once
#define HTM_IOT_ENDPOINT   "${endpoint}"
#define HTM_THING_NAME     "${thing}"
#define HTM_OWNER_ID       "${owner}"
#define HTM_TOPIC_PREFIX   "tremor/v1/${owner}/${thing}/"
static const char HTM_ROOT_CA[]     = ${raw(ca)};
static const char HTM_DEVICE_CERT[] = ${raw(cert.certificatePem)};
static const char HTM_PRIVATE_KEY[] = ${raw(cert.keyPair.PrivateKey)};
`;
writeFileSync(join(root, 'firmware/tremor_monitor/device_config.h'), header, { mode: 0o600 });
ok('firmware/tremor_monitor/device_config.h written (git-ignored)');
console.log(`\nNext: npm run sim -- --mqtt ${join('tools/aws/out', thing, 'devsim.json')}   (watch it in the IoT Core MQTT test client: tremor/v1/${owner}/${thing}/#)`);
